const messages: Record<Locale, Record<string, string>> = {
  "en-US": enUS,
  "zh-CN": zhCN,
};

export function detectLocale(languages: readonly string[] = navigator.languages): Locale {
  const preferred = languages[0]?.toLowerCase() ?? "";
  return preferred.startsWith("zh")
    ? "zh-CN"
    : "en-US";
}

export function translate(
  locale: Locale,
  messageId: string,
  values: Record<string, string | number> = {},
): string {
  const template = messages[locale][messageId] ?? messages["en-US"][messageId] ?? messageId;
  return template.replace(/\{([a-z_]+)\}/gu, (_, key: string) => String(values[key] ?? `{${key}}`));
}
